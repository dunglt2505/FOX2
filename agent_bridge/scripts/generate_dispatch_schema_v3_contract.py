"""Generate the runtime Dispatch v3 structural contract from the canonical schema."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

SOURCE_COMMIT = "8f23c3791d599e4e1f391d1dddbc9e34bd81da07"
SOURCE_PATH = "docs/agent_handoff/FOX2_LOCAL_AGENT_DISPATCH_SCHEMA_v3.json"
ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "agent_bridge/src/fox2_agent_bridge/dispatch_schema_v3_contract.py"


def source_bytes() -> bytes:
    return subprocess.run(
        ["git", "-C", str(ROOT), "show", f"{SOURCE_COMMIT}:{SOURCE_PATH}"],
        capture_output=True,
        check=True,
    ).stdout


def generate(raw: bytes) -> bytes:
    json.loads(raw)
    source_text = raw.decode("utf-8").rstrip("\r\n")
    output = (
        '"""Generated by scripts/generate_dispatch_schema_v3_contract.py; do not edit."""\n'
        "import json\n\n"
        f'SOURCE_COMMIT = {SOURCE_COMMIT!r}\n'
        f'SOURCE_PATH = {SOURCE_PATH!r}\n'
        f'SOURCE_SHA256 = {hashlib.sha256(raw).hexdigest()!r}\n\n'
        "SCHEMA_JSON = r'''"
        + source_text
        + "'''\n"
        "DISPATCH_SCHEMA_V3 = json.loads(SCHEMA_JSON)\n"
    )
    return output.encode("utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    canonical = source_bytes()
    raw = args.input.read_bytes() if args.input else canonical
    if raw != canonical:
        raise ValueError("input must contain exact pinned Dispatch v3 schema bytes")

    binding = generate(raw)
    if args.check:
        if OUTPUT.read_bytes() != binding:
            raise ValueError("DISPATCH_V3_SCHEMA_BINDING drift")
        print("DISPATCH_V3_SCHEMA_BINDING=PASS")
    else:
        OUTPUT.write_bytes(binding)


if __name__ == "__main__":
    main()
