"""Generate Bridge machine identifiers from the immutable Project Dictionary."""
import argparse
import hashlib
import json
from pathlib import Path
import pprint
import subprocess

SOURCE_COMMIT = 'b6918cced1d118dbedbd7cdf86676c16331b9314'
SOURCE_PATH = 'docs/governance/FOX2_PROJECT_DICTIONARY_v1.json'
ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'agent_bridge/src/fox2_agent_bridge/project_dictionary.py'


def source_bytes():
    return subprocess.run(['git', '-C', str(ROOT), 'show', f'{SOURCE_COMMIT}:{SOURCE_PATH}'],
                          capture_output=True, check=True).stdout


def generate(raw: bytes) -> bytes:
    dictionary = json.loads(raw)
    values = {
        'SOURCE_COMMIT': SOURCE_COMMIT, 'SOURCE_PATH': SOURCE_PATH,
        'SOURCE_SHA256': hashlib.sha256(raw).hexdigest(),
        'DICTIONARY_ID': dictionary['dictionary_id'],
        'DICTIONARY_VERSION': dictionary['dictionary_version'],
        'PROJECT_ID': dictionary['project']['id'],
        'REPOSITORY': dictionary['project']['repository'],
        'WORKSPACE_ID': dictionary['project']['workspace_id'],
        'CURRENT': dictionary['current'],
        'CURRENT_CONTRACT_SHA256': {
            key: hashlib.sha256(subprocess.run(
                ['git', '-C', str(ROOT), 'show',
                 f'{SOURCE_COMMIT}:{dictionary["current"][key]["path"]}'],
                capture_output=True, check=True).stdout).hexdigest()
            for key in ('policy', 'routing_index', 'git_first_protocol',
                        'preexec_evidence_protocol', 'preflight_receipt_schema', 'chat_preflight_intake')
        },
        'PREFLIGHT_RECEIPT_SCHEMA': json.loads(subprocess.run(
            ['git', '-C', str(ROOT), 'show',
             f'{SOURCE_COMMIT}:{dictionary["current"]["preflight_receipt_schema"]["path"]}'],
            capture_output=True, check=True).stdout),
        'CONTROL_BRANCH': dictionary['compatibility']['control_branch']['current'],
        'SUPPORTED_CONTROL_BRANCHES': tuple(dictionary['compatibility']['control_branch']['supported']),
        'CURRENT_DISPATCH_SCHEMA': dictionary['compatibility']['dispatch_schema']['current'],
        'SUPPORTED_DISPATCH_SCHEMAS': tuple(dictionary['compatibility']['dispatch_schema']['supported']),
        'DISPATCH_PATH_PATTERNS': tuple([dictionary['transport']['dispatch_paths']['current_pattern'],
                                      *dictionary['transport']['dispatch_paths']['legacy_patterns']]),
        'IDENTIFIERS': dictionary['identifiers'],
        'PROTECTED_AUTHORITY_DEFAULTS': dictionary['protected_authority_defaults'],
    }
    text = '"""Generated by scripts/generate_project_dictionary.py; do not edit."""\n\n'
    text += '\n\n'.join(f'{key} = {pprint.pformat(value, sort_dicts=True, width=100)}'
                         for key, value in values.items()) + '\n'
    return text.encode('utf-8')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw = args.input.read_bytes() if args.input else source_bytes()
    if raw != source_bytes():
        raise ValueError('input must contain exact pinned Dictionary bytes')
    binding = generate(raw)
    if args.check:
        if OUTPUT.read_bytes() != binding:
            raise ValueError('PROJECT_DICTIONARY_BINDING drift')
        print('PROJECT_DICTIONARY_BINDING=PASS')
    else:
        OUTPUT.write_bytes(binding)


if __name__ == '__main__':
    main()
